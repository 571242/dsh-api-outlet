import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = new URL('../', import.meta.url);

export function bundleClient(source, styles) {
  const cssImport = "require('./styles.css')";
  if (source.split(cssImport).length !== 2) throw new Error('Expected exactly one client stylesheet import.');
  const body = source.replace(cssImport, () => JSON.stringify(styles));
  return `// Generated by scripts/build-client.mjs; edit client/index.cjs and client/styles.css.\nwindow.__ModuleLoader__.load({\n  id: '@oracle-ai/dsh-api-outlet',\n  factory: (require) => {\n    const module = { exports: {} };\n${body}\n    return module.exports;\n  },\n});\n`;
}

export async function buildClient() {
  const [source, styles] = await Promise.all([
    readFile(new URL('client/index.cjs', root), 'utf8'),
    readFile(new URL('client/styles.css', root), 'utf8'),
  ]);
  const output = new URL('client/client.js', root);
  await writeFile(output, bundleClient(source, styles), 'utf8');
  console.log(`Built ${fileURLToPath(output)} without external build dependencies.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await buildClient();
